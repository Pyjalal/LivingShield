import type { LayerConfig } from '../types';
import { NATIONAL_DATASETS } from './catalogue';
const style = {
  color: '#38bdf8',
  weight: 1.5,
  opacity: 0.85,
  fillColor: '#38bdf8',
  fillOpacity: 0.12,
};
function gis(
  id: string,
  name: string,
  category: LayerConfig['category'],
  description: string,
  type: LayerConfig['type'] = 'geojson',
  minZoom = 9,
): LayerConfig {
  return {
    id,
    name,
    category,
    description,
    endpoint: `/api/gis?id=${id}`,
    source: 'geojson',
    type,
    minZoom,
    style: category === 'flood' ? { ...style, color: '#fb7185', fillColor: '#fb7185' } : style,
    maxFeatures: 600,
    popupFields: [
      { key: 'name', label: 'Name' },
      { key: 'LOKASI', label: 'Location' },
      { key: 'LOT', label: 'Lot' },
      { key: 'UPI', label: 'UPI' },
      { key: 'KELUASAN', label: 'Area (m²)', format: 'number' },
      { key: 'MUKIM', label: 'Mukim' },
      { key: 'GUNATANAH', label: 'Land use' },
      { key: 'NAMA_JALAN', label: 'Road' },
      { key: 'PARIT_KEJURUTERAAN', label: 'Drain' },
      { key: 'KATEGORI', label: 'Category' },
      { key: 'KAWASAN_BANJIR', label: 'Council category' },
      { key: 'KEDALAMAN_PARIT', label: 'Source depth (raw units)' },
      { key: 'LEBAR_PARIT', label: 'Source width (raw units)' },
      { key: 'tempat', label: 'Incident place' },
      { key: 'tarikh', label: 'Incident date' },
      { key: 'kedalaman__m_', label: 'Recorded depth (m)' },
    ],
    enabled: false,
    regions: ['Klang / Selangor'],
  };
}
function osm(
  id: string,
  name: string,
  category: LayerConfig['category'],
  description: string,
  type: LayerConfig['type'] = 'geojson',
): LayerConfig {
  return {
    ...gis(id, name, category, description, type, 13),
    endpoint: `/api/osm?id=${id}`,
    regions: ['Malaysia'],
    popupFields: [
      { key: 'name', label: 'Name' },
      { key: 'waterway', label: 'Waterway' },
      { key: 'building', label: 'Building' },
      { key: 'amenity', label: 'Facility' },
      { key: 'source', label: 'Source' },
    ],
  };
}
function station(
  id: string,
  name: string,
  description: string,
  category: LayerConfig['category'],
): LayerConfig {
  return {
    id,
    name,
    description,
    category,
    endpoint: `/api/stations`,
    source: 'geojson',
    type: 'point',
    style,
    pointColor: id === 'rain-gauges' ? '#38bdf8' : '#2dd4bf',
    pointRadius: 5,
    maxFeatures: 4000,
    popupFields: [
      { key: 'name', label: 'Station' },
      { key: 'state', label: 'State' },
      { key: 'district', label: 'District' },
      { key: 'waterLevel', label: 'Water level (m)' },
      { key: 'rainfall1h', label: 'Rain last hour (mm)' },
      { key: 'waterAt', label: 'Water observed (MYT)' },
      { key: 'rainAt', label: 'Rain observed (MYT)' },
      { key: 'waterStatus', label: 'Source river status' },
      { key: 'currentWater', label: 'Water reading current / online' },
      { key: 'currentRain', label: 'Rain reading current / online' },
    ],
    enabled: id === 'river-gauges',
    regions: ['Malaysia'],
  };
}
